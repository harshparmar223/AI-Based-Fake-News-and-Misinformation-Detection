"""
lime_explainer.py
=================
LIME text explainer wrapper for black-box classifiers.
"""

from __future__ import annotations

from typing import Any, Callable, List, Optional, Tuple

from loguru import logger

try:
    from lime.lime_text import LimeTextExplainer
    HAS_LIME = True
except ImportError:  # pragma: no cover
    HAS_LIME = False
    logger.warning("lime not installed – LIME explanations disabled.")


class LIMEExplainer:
    """
    Wraps LIME's LimeTextExplainer for any text classifier.

    Parameters
    ----------
    class_names:
        Human-readable class labels (default ``["Real", "Fake"]``).
    num_features:
        Maximum number of features (tokens) to include in the explanation.
    num_samples:
        Number of perturbed samples generated by LIME (default 1000).
    """

    def __init__(
        self,
        class_names: Optional[List[str]] = None,
        num_features: int = 20,
        num_samples: int = 1_000,
    ) -> None:
        if not HAS_LIME:
            raise ImportError("Install lime: pip install lime")
        self.class_names = class_names or ["Real", "Fake"]
        self.num_features = num_features
        self.num_samples = num_samples
        self._explainer = LimeTextExplainer(class_names=self.class_names)

    def explain(
        self,
        text: str,
        predict_fn: Callable[[List[str]], Any],
    ) -> List[Tuple[str, float]]:
        """
        Generate a LIME explanation for a single text instance.

        Parameters
        ----------
        text:
            Raw article text.
        predict_fn:
            A function that accepts a list of strings and returns a 2-D
            probability array of shape (n_samples, n_classes).

        Returns
        -------
        List of ``(token, weight)`` tuples sorted by absolute weight (desc).
        """
        exp = self._explainer.explain_instance(
            text,
            predict_fn,
            num_features=self.num_features,
            num_samples=self.num_samples,
            labels=[1],  # explain the FAKE class
        )
        raw = exp.as_list(label=1)
        return sorted(raw, key=lambda x: abs(x[1]), reverse=True)

