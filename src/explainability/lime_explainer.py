"""
lime_explainer.py
=================
LIME text explainer wrapper for black-box classifiers.
"""

from __future__ import annotations

import re
from typing import Any, Callable, Dict, List, Optional, Tuple

from loguru import logger

try:
    from lime.lime_text import LimeTextExplainer
    HAS_LIME = True
except ImportError:  # pragma: no cover
    HAS_LIME = False
    logger.warning("lime not installed – LIME explanations disabled.")


class LIMEExplainer:
    """
    Wraps LIME's LimeTextExplainer for any text classifier.

    Parameters
    ----------
    class_names:
        Human-readable class labels (default ``["Real", "Fake"]``).
    num_features:
        Maximum number of features (tokens) to include in the explanation.
    num_samples:
        Number of perturbed samples generated by LIME (default 300 for interactive speed).
    """

    def __init__(
        self,
        class_names: Optional[List[str]] = None,
        num_features: int = 15,
        num_samples: int = 300,
    ) -> None:
        self.class_names = class_names or ["Real", "Fake"]
        self.num_features = num_features
        self.num_samples = num_samples
        if HAS_LIME:
            self._explainer = LimeTextExplainer(
                class_names=self.class_names,
                split_expression=r"\W+",
                bow=True,
            )
        else:
            self._explainer = None

    def explain(
        self,
        text: str,
        predict_fn: Callable[[List[str]], Any],
    ) -> List[Tuple[str, float]]:
        """
        Generate a LIME explanation for a single text instance.

        Parameters
        ----------
        text:
            Raw article text.
        predict_fn:
            A function that accepts a list of strings and returns a 2-D
            probability array of shape (n_samples, n_classes).

        Returns
        -------
        List of ``(token, weight)`` tuples sorted by absolute weight (desc).
        """
        if not HAS_LIME or self._explainer is None:
            return self._heuristic_fallback(text, predict_fn)

        try:
            exp = self._explainer.explain_instance(
                text,
                predict_fn,
                num_features=self.num_features,
                num_samples=self.num_samples,
                labels=[1],  # explain the FAKE class
            )
            raw = exp.as_list(label=1)
            return sorted(raw, key=lambda x: abs(x[1]), reverse=True)
        except Exception as exc:
            logger.warning(f"LIME explain_instance failed ({exc}); using fallback attribution.")
            return self._heuristic_fallback(text, predict_fn)

    def explain_html(
        self,
        text: str,
        predict_fn: Callable[[List[str]], Any],
    ) -> Optional[str]:
        """Return full interactive LIME explanation rendered as HTML string."""
        if not HAS_LIME or self._explainer is None:
            return None
        try:
            exp = self._explainer.explain_instance(
                text,
                predict_fn,
                num_features=self.num_features,
                num_samples=self.num_samples,
                labels=[1],
            )
            return exp.as_html()
        except Exception as exc:
            logger.warning(f"Failed to generate LIME HTML explanation: {exc}")
            return None

    def explain_structured(
        self,
        text: str,
        predict_fn: Callable[[List[str]], Any],
    ) -> List[Dict[str, Any]]:
        """Return structured word attributions for clean UI badges and tables."""
        raw_list = self.explain(text, predict_fn)
        structured = []
        for word, weight in raw_list:
            pushes_toward = "FAKE" if weight > 0 else "REAL"
            structured.append({
                "word": word,
                "weight": round(float(weight), 4),
                "influence": pushes_toward,
                "color": "#ef4444" if pushes_toward == "FAKE" else "#22c55e",
            })
        return structured

    def _heuristic_fallback(
        self,
        text: str,
        predict_fn: Callable[[List[str]], Any],
    ) -> List[Tuple[str, float]]:
        """Fallback token attribution via leave-one-out perturbation."""
        tokens = list(dict.fromkeys(re.findall(r"\b[A-Za-z]{3,}\b", text.lower())))[:20]
        if not tokens:
            return []

        base_p = predict_fn([text])[0, 1]
        weights = []
        for token in tokens:
            # Mask token
            perturbed = re.sub(rf"\b{re.escape(token)}\b", "", text, flags=re.IGNORECASE)
            new_p = predict_fn([perturbed])[0, 1]
            diff = base_p - new_p  # If removing lowers fake_p, token pushed towards fake
            weights.append((token, float(diff)))

        return sorted(weights, key=lambda x: abs(x[1]), reverse=True)[:self.num_features]
